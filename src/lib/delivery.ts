/* ── Haversine ── */
function distanceKm(lat1: number, lon1: number, lat2: number, lon2: number): number {
  const R = 6371;
  const dLat = ((lat2 - lat1) * Math.PI) / 180;
  const dLon = ((lon2 - lon1) * Math.PI) / 180;
  const a =
    Math.sin(dLat / 2) ** 2 +
    Math.cos((lat1 * Math.PI) / 180) *
      Math.cos((lat2 * Math.PI) / 180) *
      Math.sin(dLon / 2) ** 2;
  return R * 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a));
}

function roundTo(value: number, step: number): number {
  return Math.round(value / step) * step;
}

/**
 * Цена доставки по расстоянию (если города нет в справочнике).
 *
 * Зоны (от Казани):
 *   0–200 км   → 350 ₽
 * 200–500 км   → 400–600 ₽  (линейная интерполяция)
 * 500–1000 км  → 600–800 ₽
 * 1000–3000 км → 800–1400 ₽
 * 3000–6000 км → 1400–2200 ₽
 * 6000+ км     → 2200–3000 ₽
 */
function priceByDistance(km: number): number {
  if (km <= 200)  return 350;
  if (km <= 500)  return 400 + (km - 200) / 300 * 200;           // 400→600
  if (km <= 1000) return 600 + (km - 500) / 500 * 200;           // 600→800
  if (km <= 3000) return 800 + (km - 1000) / 2000 * 600;         // 800→1400
  if (km <= 6000) return 1400 + (km - 3000) / 3000 * 800;        // 1400→2200
  return 2200 + (km - 6000) / 4000 * 800;                        // 2200→3000
}

/**
 * Стоимость доставки в рублях из Казани.
 *
 * @param city      — название города (из виджета Почты или вручную)
 * @param coords    — [lat, lon] ПВЗ (fallback, если города нет в справочнике)
 * @param diskCount — количество дисков в заказе (≥1)
 */
export function getDeliveryCostRub(
  city: string | null,
  coords: [number, number] | null,
  diskCount: number = 1,
): number {
  if (ONE_RUBLE_DELIVERY) return 1;

  /* 1. Ищем по городу */
  let base = 0;
  if (city) {
    const key = city.trim().toLowerCase().replace(/ё/g, 'е');
    // Пробуем точное совпадение, потом «город содержится в строке»
    if (CITY_PRICES[key] != null) {
      base = CITY_PRICES[key];
    } else {
      for (const [k, v] of Object.entries(CITY_PRICES)) {
        if (key.includes(k) || k.includes(key)) {
          base = v;
          break;
        }
      }
    }
  }

  /* 2. Если не нашли — считаем по расстоянию */
  if (base === 0 && coords) {
    const km = distanceKm(coords[0], coords[1], ORIGIN_LAT, ORIGIN_LON);
    base = priceByDistance(km);
  }

  /* 3. Если вообще нет данных — цена «до Москвы» */
  if (base === 0) base = 700;

  /* 4. Доплата за доп. диски */
  const extra = Math.max(0, diskCount - 1) * EXTRA_DISK_RUB;

  const total = base + extra;
  const clamped = Math.min(MAX_DELIVERY_RUB, Math.max(MIN_DELIVERY_RUB, total));
  return roundTo(clamped, ROUND_TO);
}

